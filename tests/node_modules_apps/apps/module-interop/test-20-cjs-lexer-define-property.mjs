import assert from 'node:assert';
import definePropertyDefault, {
  functionGetterExport,
  getterExport,
  moduleValueExport,
  namedFunctionGetterExport,
  valueExport,
  valueThenComputed,
  valueThenString,
  valueThenValue,
} from 'cjs-lexer-define-property';
import * as definePropertyNs from 'cjs-lexer-define-property';

export const run = () => {
  assert.strictEqual(valueExport, 'value');
  assert.strictEqual(moduleValueExport, 'module-value');
  assert.strictEqual(getterExport, 'getter-value');
  assert.strictEqual(functionGetterExport, 'getter-value');
  assert.strictEqual(namedFunctionGetterExport, 'getter-value');
  assert.strictEqual(valueThenValue, 'second');
  assert.strictEqual(valueThenString, 'string-wins');
  assert.strictEqual(valueThenComputed, 'computed-wins');

  assert.strictEqual(definePropertyDefault.arrowGetter, 'getter-value');
  assert.strictEqual(definePropertyDefault.stringKeyGetter, 'getter-value');
  assert.strictEqual(definePropertyDefault.stringKeyValue, 'string-key-value');
  assert.strictEqual(definePropertyDefault.shorthandValue, 'shorthand-value');
  assert.strictEqual(definePropertyDefault.computedValue, 'computed-value');
  assert.strictEqual(definePropertyDefault.multiStatementGetter, 'getter-value');
  assert.strictEqual(definePropertyDefault.helperValueDescriptor, 'getter-value');
  assert.strictEqual(definePropertyDefault.parameterGetter, 'getter-value');
  assert.strictEqual(definePropertyDefault.parameterFunctionGetter, 'getter-value');
  assert.strictEqual(definePropertyDefault.helperDescriptor, 'getter-value');
  assert.strictEqual(definePropertyDefault.nestedMemberGetter, undefined);
  assert.strictEqual(definePropertyDefault.nestedBracketGetter, undefined);
  assert.strictEqual(definePropertyDefault.duplicateGet, 'getter-value');
  assert.strictEqual(definePropertyDefault.stringThenValue, 'getter-value');
  assert.strictEqual(definePropertyDefault.computedThenValue, 'getter-value');

  assert.strictEqual(Object.hasOwn(definePropertyNs, 'arrowGetter'), false);
  assert.strictEqual(Object.hasOwn(definePropertyNs, 'stringKeyGetter'), false);
  assert.strictEqual(Object.hasOwn(definePropertyNs, 'stringKeyValue'), false);
  assert.strictEqual(Object.hasOwn(definePropertyNs, 'shorthandValue'), false);
  assert.strictEqual(Object.hasOwn(definePropertyNs, 'computedValue'), false);
  assert.strictEqual(Object.hasOwn(definePropertyNs, 'multiStatementGetter'), false);
  assert.strictEqual(Object.hasOwn(definePropertyNs, 'helperValueDescriptor'), false);
  assert.strictEqual(Object.hasOwn(definePropertyNs, 'parameterGetter'), false);
  assert.strictEqual(Object.hasOwn(definePropertyNs, 'parameterFunctionGetter'), false);
  assert.strictEqual(Object.hasOwn(definePropertyNs, 'helperDescriptor'), false);
  assert.strictEqual(Object.hasOwn(definePropertyNs, 'nestedMemberGetter'), false);
  assert.strictEqual(Object.hasOwn(definePropertyNs, 'nestedBracketGetter'), false);
  assert.strictEqual(Object.hasOwn(definePropertyNs, 'duplicateGet'), false);
  assert.strictEqual(Object.hasOwn(definePropertyNs, 'stringThenValue'), false);
  assert.strictEqual(Object.hasOwn(definePropertyNs, 'computedThenValue'), false);

  return 'PASS: CJS lexer parity Object.defineProperty descriptor patterns';
};
