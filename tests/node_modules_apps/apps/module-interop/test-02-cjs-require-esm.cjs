const assert = require('node:assert');

exports.run = () => {
  const esm = require('esm-sync');
  const esmDefault = typeof esm === 'function' ? esm : esm.default;
  assert.strictEqual(typeof esmDefault, 'function');
  assert.strictEqual(esmDefault(), 'default-call');
  assert.strictEqual(esm.answer, 42);
  assert.strictEqual(esm.named, 'named');
  assert.strictEqual(esm.count, 0);
  esm.inc();
  assert.strictEqual(esm.count, 1);

  assert.deepStrictEqual(Object.keys(esm), ['__esModule', 'answer', 'count', 'default', 'inc', 'named']);
  assert.strictEqual(Object.getPrototypeOf(esm), null);
  assert.strictEqual(Object.isSealed(esm), true);
  assert.strictEqual(Object.isExtensible(esm), false);
  assert.deepStrictEqual(Object.getOwnPropertyDescriptor(esm, '__esModule'), {
    value: true,
    writable: true,
    enumerable: true,
    configurable: false,
  });
  assert.deepStrictEqual(Object.getOwnPropertyDescriptor(esm, 'default'), {
    value: esm.default,
    writable: true,
    enumerable: true,
    configurable: false,
  });
  assert.deepStrictEqual(Object.getOwnPropertyDescriptor(esm, 'count'), {
    value: 1,
    writable: true,
    enumerable: true,
    configurable: false,
  });
  esm.named = 'changed';
  assert.strictEqual(esm.named, 'named');
  assert.throws(() => Object.defineProperty(esm, 'extra', { value: true }), TypeError);

  const explicit = require('esm-sync/explicit-es-module');
  assert.strictEqual(explicit.__esModule, false);
  assert.deepStrictEqual(Object.keys(explicit), ['__esModule', 'default', 'named']);
  assert.deepStrictEqual(Object.getOwnPropertyDescriptor(explicit, '__esModule'), {
    value: false,
    writable: true,
    enumerable: true,
    configurable: false,
  });

  const override = require('esm-sync/module-exports-override');
  assert.deepStrictEqual(override, { answer: 42 });
  assert.notStrictEqual(Object.getPrototypeOf(override), null);
  assert.strictEqual(Object.isSealed(override), false);

  return 'PASS: CJS requires an installed synchronous ESM package';
};
