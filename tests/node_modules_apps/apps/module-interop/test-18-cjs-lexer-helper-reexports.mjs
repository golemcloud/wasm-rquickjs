import assert from 'node:assert';
import helperDefault, {
  depAlpha,
  depBeta,
  depGamma,
  depDelta,
  own as helperOwn,
} from 'cjs-lexer-helper-reexports';
import packageReexportDefault, {
  alpha as packageAlpha,
  beta as packageBeta,
} from 'cjs-lexer-package-reexport';
import * as packageReexportNs from 'cjs-lexer-package-reexport';

const negativeNs = await import('cjs-lexer-helper-reexports-negative');

export const run = () => {
  assert.strictEqual(depAlpha, 'dep-alpha');
  assert.strictEqual(depBeta, 'dep-beta');
  assert.strictEqual(depGamma, 'dep-gamma');
  assert.strictEqual(depDelta, 'dep-delta');
  assert.strictEqual(helperOwn, 'own-value');
  assert.strictEqual(helperDefault.depDelta, 'dep-delta');
  assert.strictEqual(packageAlpha, 'pkg-alpha');
  assert.strictEqual(packageBeta, 'pkg-beta');
  assert.strictEqual(packageReexportDefault.alpha, 'pkg-alpha');
  assert.strictEqual(packageReexportDefault['runtime-only'], 'pkg-runtime-only');
  // Node 23+ adds a 'module.exports' export to CommonJS namespaces. The raw test runs on the
  // host baseline Node and in the runtime target, so expect the exact keys of the running Node.
  const nodeMajor = Number(process.versions.node.split('.')[0]);
  assert.deepStrictEqual(
    Object.keys(packageReexportNs).sort(),
    nodeMajor >= 23 ? ['alpha', 'beta', 'default', 'module.exports'] : ['alpha', 'beta', 'default'],
  );

  assert.strictEqual(negativeNs.default.depNested, 'dep-nested');
  assert.strictEqual(negativeNs.default.depDynamic, 'dep-dynamic');
  assert.strictEqual(Object.hasOwn(negativeNs, 'depNested'), false);
  assert.strictEqual(Object.hasOwn(negativeNs, 'depDynamic'), false);
  assert.strictEqual(Object.hasOwn(negativeNs, 'own'), true);

  return 'PASS: CJS lexer parity helper reexport patterns';
};
