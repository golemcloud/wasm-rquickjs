import assert from 'node:assert';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import rootImport from 'resolver-parity';
import featureImport from 'resolver-parity/features/alpha';
import importsEsm from 'resolver-parity/imports/esm';

const require = createRequire(import.meta.url);

function requireResolveUrl(specifier) {
  return pathToFileURL(require.resolve(specifier)).href;
}

export const run = () => {
  assert.deepStrictEqual(rootImport, require('resolver-parity'));
  assert.deepStrictEqual(featureImport, require('resolver-parity/features/alpha'));
  assert.strictEqual(import.meta.resolve('resolver-parity'), requireResolveUrl('resolver-parity'));
  assert.strictEqual(
    import.meta.resolve('resolver-parity/features/alpha'),
    requireResolveUrl('resolver-parity/features/alpha'),
  );

  const importsCjs = require('resolver-parity/imports/cjs');
  assert.deepStrictEqual(importsEsm.value, importsCjs.value);
  assert.strictEqual(importsEsm.resolved, importsCjs.resolved);

  return 'PASS: cross-path resolver parity holds for package exports, wildcard exports, and package imports';
};
