import assert from 'node:assert';
import objectLiteralDefault, {
  a as literalA,
  b as literalB,
  d as literalD,
  depAlpha as literalDepAlpha,
  depBeta as literalDepBeta,
} from 'cjs-lexer-object-literal';
import callbackDefault, {
  depAlpha as callbackDepAlpha,
  depBeta as callbackDepBeta,
  own as callbackOwn,
} from 'cjs-lexer-keys-reexport';
import requireValueDefault, {
  a as requireValueA,
  b as requireValueB,
} from 'cjs-lexer-object-require-value';
import * as requireValueNs from 'cjs-lexer-object-require-value';
import memberValueDefault, {
  before as memberBefore,
  memberValue,
} from 'cjs-lexer-object-member-value';
import * as memberValueNs from 'cjs-lexer-object-member-value';
import nestedValueDefault, { nestedValue } from 'cjs-lexer-object-member-value/nested.cjs';
import * as nestedValueNs from 'cjs-lexer-object-member-value/nested.cjs';
import bracketValueDefault, { bracketValue } from 'cjs-lexer-object-member-value/bracket.cjs';
import * as bracketValueNs from 'cjs-lexer-object-member-value/bracket.cjs';
import callValueDefault, { callValue } from 'cjs-lexer-object-member-value/call.cjs';
import * as callValueNs from 'cjs-lexer-object-member-value/call.cjs';
import binaryValueDefault, { binaryValue } from 'cjs-lexer-object-member-value/binary.cjs';
import * as binaryValueNs from 'cjs-lexer-object-member-value/binary.cjs';
import optionalValueDefault, { optionalValue } from 'cjs-lexer-object-member-value/optional.cjs';
import * as optionalValueNs from 'cjs-lexer-object-member-value/optional.cjs';
import primitiveValueDefault, {
  trueValue,
  falseValue,
  nullValue,
  undefinedValue,
  after as primitiveAfter,
} from 'cjs-lexer-object-member-value/primitive.cjs';

export const run = () => {
  assert.strictEqual(literalA, 1);
  assert.strictEqual(literalB, 2);
  assert.strictEqual(literalD, 4);
  assert.strictEqual(literalDepAlpha, 'dep-alpha');
  assert.strictEqual(literalDepBeta, 'dep-beta');
  assert.strictEqual(objectLiteralDefault.depAlpha, 'dep-alpha');

  assert.strictEqual(callbackDepAlpha, 'dep-alpha');
  assert.strictEqual(callbackDepBeta, 'dep-beta');
  assert.strictEqual(callbackOwn, 'own-value');
  assert.strictEqual(callbackDefault.own, 'own-value');

  assert.strictEqual(requireValueA, 1);
  assert.deepStrictEqual(requireValueB, { depAlpha: 'dep-alpha' });
  assert.strictEqual(Object.hasOwn(requireValueNs, 'depAlpha'), false);
  assert.strictEqual(requireValueDefault.afterRequire, 3);
  assert.strictEqual(Object.hasOwn(requireValueNs, 'afterRequire'), false);

  assert.strictEqual(memberBefore, 'before-value');
  assert.strictEqual(memberValue, 'member-value');
  assert.strictEqual(memberValueDefault.after, 'not-exported');
  assert.strictEqual(Object.hasOwn(memberValueNs, 'after'), false);

  assert.strictEqual(nestedValue, 'nested-value');
  assert.strictEqual(nestedValueDefault.after, 'not-exported');
  assert.strictEqual(Object.hasOwn(nestedValueNs, 'after'), false);

  assert.strictEqual(bracketValue, 'member-value');
  assert.strictEqual(bracketValueDefault.after, 'not-exported');
  assert.strictEqual(Object.hasOwn(bracketValueNs, 'after'), false);

  assert.strictEqual(callValue, 'member-value');
  assert.strictEqual(callValueDefault.after, 'not-exported');
  assert.strictEqual(Object.hasOwn(callValueNs, 'after'), false);

  assert.strictEqual(binaryValue, 2);
  assert.strictEqual(binaryValueDefault.after, 'not-exported');
  assert.strictEqual(Object.hasOwn(binaryValueNs, 'after'), false);

  assert.strictEqual(optionalValue, 'member-value');
  assert.strictEqual(optionalValueDefault.after, 'not-exported');
  assert.strictEqual(Object.hasOwn(optionalValueNs, 'after'), false);

  assert.strictEqual(trueValue, true);
  assert.strictEqual(falseValue, false);
  assert.strictEqual(nullValue, null);
  assert.strictEqual(undefinedValue, undefined);
  assert.strictEqual(primitiveAfter, 'after-value');
  assert.strictEqual(primitiveValueDefault.after, 'after-value');

  return 'PASS: CJS lexer parity object-literal and keys reexport patterns';
};
