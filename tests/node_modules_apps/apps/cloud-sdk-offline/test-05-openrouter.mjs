import assert from 'node:assert';
import { HTTPClient, OpenRouter } from '@openrouter/sdk';

export const run = async () => {
  let request;
  const httpClient = new HTTPClient({
    fetcher: async (input) => {
      request = input;
      return new Response(JSON.stringify({
        choices: [{
          finish_reason: 'stop',
          index: 0,
          message: {
            content: 'offline reply',
            role: 'assistant',
          },
        }],
        created: 1,
        id: 'generation-test',
        model: 'openai/gpt-test',
        object: 'chat.completion',
        system_fingerprint: null,
      }), {
        status: 200,
        headers: { 'content-type': 'application/json' },
      });
    },
  });
  const client = new OpenRouter({
    apiKey: 'sk-test',
    httpClient,
  });

  const result = await client.chat.send({
    chatRequest: {
      messages: [{ role: 'user', content: 'Hello' }],
      model: 'openai/gpt-test',
    },
  });

  assert.strictEqual(request.method, 'POST');
  assert.strictEqual(new URL(request.url).pathname, '/api/v1/chat/completions');
  assert.strictEqual(request.headers.get('authorization'), 'Bearer sk-test');
  assert.strictEqual(result.choices[0].message.content, 'offline reply');
  assert.strictEqual(result.choices[0].finishReason, 'stop');
  return 'PASS: OpenRouter SDK sends and parses an offline chat request';
};
