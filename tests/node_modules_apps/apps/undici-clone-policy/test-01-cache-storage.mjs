import assert from 'node:assert/strict';
import undici from 'undici';

export async function run() {
    const {caches} = undici;
    const name = 'wrqjs-clone-policy';
    assert.equal(await caches.has(name), false);
    const cache = await caches.open(name);
    assert.equal(await caches.has(name), true);
    assert.deepEqual(await caches.keys(), [name]);
    for (const value of [caches, cache]) {
        assert.throws(() => structuredClone({nested: [value]}), {name: 'DataCloneError', code: 25});
    }
    assert.equal(await caches.delete(name), true);
    assert.equal(await caches.has(name), false);
    return 'PASS: unpatched undici 8.10.2 root and CacheStorage/Cache semantics';
}
