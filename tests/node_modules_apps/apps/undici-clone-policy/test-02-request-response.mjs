import assert from 'node:assert/strict';
import undici from 'undici';

export async function run() {
    const {Request, Response, Headers, FormData} = undici;
    const request = new Request('https://example.invalid/api', {method: 'POST', body: 'request payload', headers: {'x-test': 'yes'}});
    const requestClone = request.clone();
    assert.equal(requestClone.method, 'POST');
    assert.equal(requestClone.headers.get('x-test'), 'yes');
    assert.equal(await request.text(), 'request payload');
    assert.equal(await requestClone.text(), 'request payload');
    const response = Response.json({ok: true}, {status: 201});
    const responseClone = response.clone();
    assert.equal(responseClone.status, 201);
    assert.deepEqual(await response.json(), {ok:true});
    assert.deepEqual(await responseClone.json(), {ok:true});
    for (const value of [request, response, new Headers(), new FormData()])
        assert.throws(() => structuredClone({value}), {name:'DataCloneError', code:25});
    return 'PASS: undici Request/Response body clones and genuine uncloneable objects';
}
