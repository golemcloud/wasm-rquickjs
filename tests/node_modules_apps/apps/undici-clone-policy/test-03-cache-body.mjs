import assert from 'node:assert/strict';
import undici from 'undici';

export async function run() {
    const {caches, Request, Response} = undici;
    const name = 'wrqjs-body-cache';
    const cache = await caches.open(name);
    const request = new Request('https://example.invalid/offline');
    await cache.put(request, new Response('cached bytes', {headers:{'content-type':'text/plain'}}));
    const first = await cache.match(request);
    assert.equal(await first.text(), 'cached bytes');
    const second = await cache.match(request.url);
    assert.equal(await second.text(), 'cached bytes');
    assert.equal(await cache.delete(request), true);
    assert.equal(await cache.match(request), undefined);
    assert.equal(await caches.delete(name), true);
    return 'PASS: undici cache stores independent response bodies without network';
}
